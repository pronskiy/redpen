#!/usr/bin/env bash
#
# Translate prompt checks — SPEC.md step F1.5.
#
# Runs the translate prompt over docs/translate-fixtures, checks direction and notes
# mechanically, and writes every output to a sheet for reading by eye.
#
#   evals/translate.sh                     # the model, effort and prompt the app would use
#   evals/translate.sh -m claude-haiku-5-5 # another model
#   evals/translate.sh -e medium           # another effort
#   evals/translate.sh -p my-prompt.md     # another prompt
#
# A sibling of run.sh rather than a mode of it: run.sh is built around the critique's tag
# block and rubric, none of which a translation has.
set -uo pipefail

FIXTURES="docs/translate-fixtures"
PROMPT_FILE=""
MODEL=""
EFFORT=""
CONFIG_JSON="$HOME/Library/Application Support/redpen/config.json"

while getopts "p:m:e:h" opt; do
  case "$opt" in
    p) PROMPT_FILE="$OPTARG" ;;
    m) MODEL="$OPTARG" ;;
    e) EFFORT="$OPTARG" ;;
    h) sed -n '3,13p' "$0"; exit 0 ;;
    *) exit 2 ;;
  esac
done

for tool in jq curl perl; do
  command -v "$tool" >/dev/null || { echo "need $tool" >&2; exit 1; }
done

cfg() {
  [ -f "$CONFIG_JSON" ] || { echo ""; return; }
  jq -r --arg k "$1" '.[$k] // empty' "$CONFIG_JSON" 2>/dev/null
}

# Same defaults as config.rs, so a bare run checks what the app ships.
API_KEY="${ANTHROPIC_API_KEY:-$(cfg api_key)}"
BASE_URL="${ANTHROPIC_BASE_URL:-$(cfg base_url)}"
BASE_URL="${BASE_URL:-https://api.anthropic.com}"; BASE_URL="${BASE_URL%/}"
[ -n "$MODEL" ] || MODEL="$(cfg translate_model)"; MODEL="${MODEL:-claude-sonnet-5}"
[ -n "$EFFORT" ] || EFFORT="$(cfg translate_effort)"; EFFORT="${EFFORT:-low}"
[ -n "$PROMPT_FILE" ] || PROMPT_FILE="$(cfg translate_prompt_path)"; PROMPT_FILE="${PROMPT_FILE:-prompts/translate.md}"
[ -f "$PROMPT_FILE" ] || { echo "no prompt file: $PROMPT_FILE" >&2; exit 1; }
[ -n "$API_KEY" ] || { echo "no API key: set api_key in $CONFIG_JSON or export ANTHROPIC_API_KEY" >&2; exit 1; }

WORK="evals/.out/translate-$MODEL-$EFFORT"
SHEET="$WORK.md"
mkdir -p "$WORK"

FILES=()
while IFS= read -r f; do FILES+=("$f"); done < <(find "$FIXTURES" -maxdepth 1 -name '*.txt' | sort)

echo "prompt   $PROMPT_FILE"
echo "model    $MODEL"
echo "effort   $EFFORT"
echo "fixtures ${#FILES[@]} in $FIXTURES"
echo

call_one() {
  local src="$1" base out
  base="$(basename "$src" .txt)"; out="$WORK/$base"
  jq -n --rawfile sys "$PROMPT_FILE" --rawfile txt "$src" --arg model "$MODEL" --arg effort "$EFFORT" '{
    model: $model, max_tokens: 4000, system: $sys,
    messages: [{role: "user", content: ($txt | rtrimstr("\n"))}],
    thinking: {type: "adaptive"}, output_config: {effort: $effort}
  }' > "$out.req.json"
  curl -sS --max-time 120 -w '%{time_total}' -o "$out.res.json" "$BASE_URL/v1/messages" \
    -H "x-api-key: $API_KEY" -H "anthropic-version: 2023-06-01" -H "content-type: application/json" \
    -d @"$out.req.json" > "$out.secs" 2>"$out.err"
  jq -r '[.content[]? | select(.type=="text") | .text] | join("")' "$out.res.json" > "$out.txt" 2>/dev/null
}

for src in "${FILES[@]}"; do call_one "$src" & done
wait

# Checks one output against what its file name promises. Prints failures, one per line.
check() {
  perl -CSD -Mutf8 -e '
    my ($name, $path) = @ARGV;
    open my $fh, "<:encoding(UTF-8)", $path or do { print "no output\n"; exit };
    my $all = do { local $/; <$fh> };
    my ($body, $notes) = split /^---\s*$/m, $all, 2;
    $notes //= "";
    my ($lang, $kind) = split /-/, $name;
    my $cyr = sub { $_[0] =~ /\p{Cyrillic}/ };
    if ($lang eq "en") { print "translation is not in Russian\n" unless $cyr->($body) }
    else              { print "translation is not in English\n" if $cyr->($body) }
    my @n = grep { /^\s*-\s*\*\*/ } split /\n/, $notes;
    if ($kind eq "idiom") { print "idiom got no note\n" unless @n }
    else                  { print "plain text got notes\n" if $all =~ /^---\s*$/m }
    for (@n) { my ($t) = /\*\*.*?\*\*\s*[—–-]\s*(.*)/; print "note not in Russian: $_\n" unless $cyr->($t // "") }
    print "leaked markup or a label\n" if $all =~ /<\/?(source|output|example)>|\bso (English|Russian)\b|^Source\b/mi;
  ' "$1" "$2"
}

pass=0
{
  echo "# Translate fixtures — \`$MODEL\` @ \`$EFFORT\`"
  echo
  echo "Prompt \`$PROMPT_FILE\` · generated by \`evals/translate.sh\`"
  echo
  echo "| fixture | secs | checks |"
  echo "|---|---|---|"
} > "$SHEET"
for src in "${FILES[@]}"; do
  base="$(basename "$src" .txt)"; out="$WORK/$base"
  secs="$(cat "$out.secs" 2>/dev/null)"; secs="${secs:-?}"
  if jq -e '.type == "error"' "$out.res.json" >/dev/null 2>&1; then
    fails="API error: $(jq -r '.error.message' "$out.res.json")"
  else
    fails="$(check "$base" "$out.txt")"
  fi
  if [ -z "$fails" ]; then pass=$((pass + 1)); verdict="✅"; else verdict="❌ ${fails//$'\n'/; }"; fi
  printf '  %-14s %6ss  %s\n' "$base" "$secs" "$verdict"
  echo "| \`$base\` | $secs | $verdict |" >> "$SHEET"
done
{
  echo
  for src in "${FILES[@]}"; do
    base="$(basename "$src" .txt)"
    echo "## \`$base\`"; echo; echo '> '"$(cat "$src")"; echo; cat "$WORK/$base.txt"; echo; echo
  done
} >> "$SHEET"

echo
echo "passed $pass/${#FILES[@]} · sheet: $SHEET"
[ "$pass" -eq "${#FILES[@]}" ]
